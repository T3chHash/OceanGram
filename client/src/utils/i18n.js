const LANGUAGE_STORAGE_KEY = "oceangram-language";
const listeners = new Set();

function getInitialLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved && TRANSLATIONS[saved]) return saved;
    const browserLang = (navigator.language || "").slice(0, 2).toLowerCase();
    if (TRANSLATIONS[browserLang]) return browserLang;
  } catch (_) {}
  return "en";
}

let currentLang = getInitialLanguage();

export function setLanguage(code) {
  if (!TRANSLATIONS[code]) return;
  currentLang = code;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === code);
    if (typeof document !== "undefined") {
      document.documentElement.lang = code;
      document.documentElement.dir = meta?.dir || "ltr";
    }
  } catch (_) {}
  listeners.forEach((listener) => listener(currentLang));
}

export function getLanguage() {
  return currentLang;
}

export function t(key, fallback = "") {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}

export function useI18n() {
  const [lang, setLangState] = useState(currentLang);

  useEffect(() => {
    const handler = (newLang) => setLangState(newLang);
    listeners.add(handler);
    return () => listeners.delete(handler);
  }, []);

  const meta = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];

  return {
    lang,
    setLanguage,
    t: (key, fallback) => {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
      return dict[key] || TRANSLATIONS.en[key] || fallback || key;
    },
    isRtl: meta.dir === "rtl",
    languages: SUPPORTED_LANGUAGES,
  };
}
